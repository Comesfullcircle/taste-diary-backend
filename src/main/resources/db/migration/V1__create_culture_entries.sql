CREATE TABLE culture_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    category VARCHAR(30) NOT NULL,
    experienced_on DATE NOT NULL,
    review TEXT,
    rating NUMERIC(2, 1),
    expense_amount NUMERIC(12, 0) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_culture_entries_title CHECK (length(trim(title)) > 0),
    CONSTRAINT ck_culture_entries_category
        CHECK (category IN ('MOVIE', 'EXHIBITION', 'PERFORMANCE', 'BOOK', 'OTHER')),
    CONSTRAINT ck_culture_entries_review CHECK (length(review) <= 10000),
    CONSTRAINT ck_culture_entries_rating
        CHECK (rating BETWEEN 0 AND 5 AND mod(rating, 0.5) = 0),
    CONSTRAINT ck_culture_entries_expense CHECK (expense_amount >= 0)
);

CREATE INDEX idx_culture_entries_experienced_on_id
    ON culture_entries (experienced_on DESC, id DESC);
